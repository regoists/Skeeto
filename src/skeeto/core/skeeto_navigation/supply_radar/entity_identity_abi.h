// Serial entity identity for the live display cache; no audio dependency.
inline bool EntityIdentityABI(void* entities){
    auto base=(unsigned char*)GetModuleHandleW(L"client.dll");
    // Both full-handle and index getters use 16-byte entity records at
    // entities+(index-1001h)*16. Verify the entire handle getter, plus the
    // index getter that confirms the same record layout and conversion.
    const unsigned char handle[]={0x55,0x8b,0xec,0x8b,0x55,0x08,0x83,0xfa,0xff,0x74,0x21,0x8b,0xc2,0x25,0xff,0x0f,0,0,0x2d,0x01,0x10,0,0,0xc1,0xe0,0x04,0x03,0xc1,0x74,0x0e,0xc1,0xea,0x0c,0x39,0x50,0x04,0x75,0x06,0x8b,0,0x5d,0xc2,0x04,0,0x33,0xc0,0x5d,0xc2,0x04,0};
    const unsigned char index[]={0x55,0x8b,0xec,0x8b,0x45,0x08,0x85,0xc0,0x78,0x20,0x3d,0,0x10,0,0,0x7d,0x19,0x05,0xff,0xef,0xff,0xff,0x03,0xc0,0x8b,0x0c,0xc1,0x85,0xc9,0x74,0x0b,0x8b,0x01,0x8b,0x50,0x18,0xff,0xd2,0x5d,0xc2,0x04,0};
    return base&&EntityHandleABI(entities)&&MethodOK(entities,3)&&(*(void***)entities)[3]==base+0xb8dc0&&radar_abi::EqualBytes(base+0xbb4c0,handle,sizeof handle)&&radar_abi::EqualBytes(base+0xb8dc0,index,sizeof index);
}
inline unsigned EntitySerialKey(void* entities,int index,void* object){
    if(index<1||index>=2048||unsigned(entities)<0x10010u||!object)return 0;
    auto record=(unsigned char*)entities+(index-0x1001)*16;
    if(!Readable(record,8)||!*(void**)record)return 0;
    unsigned serial=*(unsigned*)(record+4);if(serial>0xfffffu)return 0;
    unsigned handle=(serial<<12)|unsigned(index);
    return VCall<void*(__thiscall*)(void*,unsigned)>(entities,4)(entities,handle)==object?handle:0;
}
